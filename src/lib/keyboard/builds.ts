/**
 * Danh mục build phím thật (kiểu "sound profile" của các shop): mỗi build gồm
 *  - thông số linh kiện thật (tra từ trang hãng/shop/review),
 *  - gói tiếng thu từ chính build đó (public/sounds/<soundPackId>, tạo bằng `npm run sounds`),
 *  - ảnh thật (public/builds/<id>.jpg; ảnh chủ dự án thả vào pics/<tên mẫu>/ được đồng bộ bằng `npm run photos`),
 *  - cách dựng 3D soi theo ảnh thật: layout, màu vỏ/keycap (kể cả màu theo hàng, phím nhấn riêng, keycap trong
 *    hoặc carbon forged), chất liệu, dáng vỏ (shellStyle), profile keycap, module phần cứng (núm, con lăn,
 *    màn hình, đèn báo, badge — xem modules.ts),
 *  - tuỳ chọn modelUrl: file .glb thật trong public/models/ (thiếu hoặc lỗi thì dựng bằng code).
 */

const hex = z.string().regex(/^#[0-9a-f]{6}$/i);

export const buildSchema = z.object({
  id: z.string().regex(/^[a-z0-9-]+$/),
  /** Tên bàn phím */
  name: z.string().min(1),
  /** Đặc điểm nổi bật ngắn: kiểu mount, switch đặc biệt… */
  tags: z.array(z.string()).max(3),
  soundPackId: z.string(),
  /** Video gốc của bản thu */
  sourceUrl: z.string().url(),
  /** File .glb thật (public/models/…) thay cho bản dựng bằng code */
  modelUrl: z
    .string()
    .regex(/^\/models\/[\w.-]+\.glb$/, 'modelUrl phải có dạng /models/<ten-file>.glb')
    .optional(),
  specs: z.object({
    case: z.string(),
    mount: z.string(),
    plate: z.string(),
    foam: z.string(),
    switch: z.string(),
    keycap: z.string(),
  }),
  look: z
    .object({
      layout: z.enum(KEYBOARD_LAYOUTS),
      caseMaterial: z.enum(['aluminum', 'plastic', 'polycarbonate', 'wood', 'acrylic']),
      caseColor: hex,
      keycapColor: hex,
      keycapModifierColor: hex,
      keycapAccentColor: hex,
      plateMaterial: z.enum(['aluminum', 'polycarbonate', 'pom', 'fr4']),
      switchType: z.enum(['linear', 'tactile', 'clicky', 'silent_linear']),
      caseShape: z.object({
        bezel: z.number().min(0.08).max(0.4),
        cornerRadius: z.number().min(0.02).max(0.3),
        /** Suy ra từ modules (có module knob) — giữ để bản build đã lưu đọc được */
        knob: z.boolean().optional(),
      }),
      shellStyle: z.enum(SHELL_STYLES).default('default'),
      keycapProfile: z.enum(KEYCAP_PROFILES).default('cherry'),
      /** Núm xoay, con lăn, màn hình, đèn báo, badge, ô trống — đặt đúng chỗ như ảnh thật */
      modules: z.array(moduleSchema).default([]),
      /** Màu keycap theo hàng (hàng F → hàng dưới cùng): keycap gradient hoặc phối từng hàng */
      keycapRows: z.array(hex).min(2).max(6).optional(),
      /** Ép từng phím (KeyboardEvent.code) sang màu nhấn / bổ trợ / chữ */
      accentKeys: z.array(z.string()).optional(),
      modifierKeys: z.array(z.string()).optional(),
      alphaKeys: z.array(z.string()).optional(),
      /** Màu chữ in riêng (mặc định tự suy theo độ sáng keycap) */
      legendColor: hex.optional(),
      /** PBT nhám, nhựa trong (jelly) hoặc carbon forged */
      keycapFinish: z.enum(['pbt', 'translucent', 'forged-carbon']).default('pbt'),
      /** Chỉ phím nhấn là keycap nhựa trong (CIDOO QK61/QK75: Esc + Enter hồng trong) */
      jellyAccent: z.boolean().default(false),
      /** Màu đèn ruột hắt qua vỏ trong mờ / khung skeletal */
      glowColor: hex.optional(),
      /** Dải đèn RGB trên vỏ: mép trước (Nut108), hai hông (F87 Pro), mặt sau (Nut87) */
      lightStrip: z.enum(['none', 'front', 'sides', 'rear']).default('none'),
      /** Màu switch thật, lấy theo ảnh sản phẩm/review; không tra được thì bỏ trống (dùng màu mặc định) */
      switchColors: z
        .object({ top: hex, bottom: hex, stem: hex, topOpacity: z.number().min(0.1).max(1) })
        .optional(),
      /** Màu solder mask PCB thật (theo video tháo máy); bỏ trống = xanh lá mặc định */
      pcbColor: hex.optional(),
      /** Màu foam plate thật (theo video tháo máy); bỏ trống = Poron xám than mặc định */
      foamColor: hex.optional(),
    })
    .transform((look) => ({
      ...look,
      caseShape: { ...look.caseShape, knob: look.modules.some((module) => module.kind === 'knob') },
    })),
});

